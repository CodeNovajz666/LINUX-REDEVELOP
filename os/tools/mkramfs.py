#!/usr/bin/env python3
"""Pack built user ELF programs into a ramfs initrd image (C source file).

Image format (little-endian, read by kernel/fs/ramfs.c):
    header  { magic 'NRFS', node_count, data_size }
    entries { path[64], offset, size } * node_count
    blob    (concatenated file contents)

Usage: mkramfs.py out.c path1=path1 path2=path2 ...
"""
import sys, os, struct

MAGIC = 0x4E524653          # 'NRFS'

def emit(files, out_path):
    # files: list of (path, src_path)
    entries = []
    blob = bytearray()
    for path, src in files:
        with open(src, 'rb') as f:
            data = f.read()
        entries.append((path, len(blob), len(data)))
        blob.extend(data)

    hdr = struct.pack('<III', MAGIC, len(entries), len(blob))
    ent = b''.join(
        struct.pack('<64sII', p.encode(), off, size)
        for p, off, size in entries)

    img = hdr + ent + bytes(blob)

    lines = []
    lines.append('/* generated by tools/mkramfs.py -- do not edit */')
    lines.append('#include <stdint.h>')
    lines.append('')
    lines.append(f'const unsigned char ramfs_img[{len(img)}] = {{')
    for i in range(0, len(img), 16):
        chunk = ', '.join(f'0x{b:02X}' for b in img[i:i+16])
        lines.append(f'    {chunk},')
    lines.append('};')
    lines.append(f'const unsigned int ramfs_img_size = {len(img)};')
    lines.append('')
    os.makedirs(os.path.dirname(out_path), exist_ok=True)
    with open(out_path, 'w', newline='\n') as f:
        f.write('\n'.join(lines))
    print(f'  ramfs image: {out_path} ({len(img)} bytes, {len(entries)} files)')

if __name__ == '__main__':
    args = sys.argv[1:]
    out_path = args[0]
    pairs = []
    for a in args[1:]:
        if '=' in a:
            path, src = a.split('=', 1)
        else:
            src = a
            path = '/bin/' + os.path.splitext(os.path.basename(src))[0]
        pairs.append((path, src))
    emit(pairs, out_path)
